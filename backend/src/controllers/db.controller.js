const { exec } = require('child_process');
const path = require('path');
const fs = require('fs');

/**
 * Controller for database backup and restore operations
 */
const backup = async (req, res) => {
    try {
        const { DB_USER, DB_PASSWORD, DB_NAME, DB_HOST, DB_PORT } = process.env;
        const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
        const filename = `backup-${DB_NAME}-${timestamp}.sql`;

        // PGPASSWORD is used to provide the password to pg_dump without a prompt
        const cmd = `PGPASSWORD='${DB_PASSWORD}' pg_dump -h ${DB_HOST} -p ${DB_PORT} -U ${DB_USER} ${DB_NAME}`;

        res.setHeader('Content-Type', 'application/sql');
        res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);

        const dumpProcess = exec(cmd);

        dumpProcess.stdout.pipe(res);

        dumpProcess.stderr.on('data', (data) => {
            console.error(`pg_dump stderr: ${data}`);
        });

        dumpProcess.on('error', (error) => {
            console.error(`pg_dump error: ${error.message}`);
            if (!res.headersSent) {
                res.status(500).json({ error: 'Error al generar el backup' });
            }
        });

    } catch (error) {
        console.error('Backup failed:', error);
        if (!res.headersSent) {
            res.status(500).json({ error: 'Error interno del servidor' });
        }
    }
};

const restore = async (req, res) => {
    if (!req.file) {
        return res.status(400).json({ error: 'No se ha subido ningún archivo' });
    }

    const { DB_USER, DB_PASSWORD, DB_NAME, DB_HOST, DB_PORT } = process.env;
    const filePath = req.file.path;

    try {
        // We use psql to restore the SQL dump
        // Note: This assumes the dump contains standard SQL (like those generated by pg_dump)
        // For production use, more robust error handling and validation would be needed.
        const cmd = `PGPASSWORD='${DB_PASSWORD}' psql -h ${DB_HOST} -p ${DB_PORT} -U ${DB_USER} -d ${DB_NAME} -f ${filePath}`;

        exec(cmd, (error, stdout, stderr) => {
            // Delete the temporary file after restoration attempt
            fs.unlinkSync(filePath);

            if (error) {
                console.error(`psql error: ${error.message}`);
                console.error(`psql stderr: ${stderr}`);
                return res.status(500).json({ error: 'Error al restaurar la base de datos', details: stderr });
            }

            console.log(`psql stdout: ${stdout}`);
            res.json({ message: 'Base de datos restaurada correctamente' });
        });
    } catch (error) {
        console.error('Restore failed:', error);
        if (fs.existsSync(filePath)) fs.unlinkSync(filePath);
        res.status(500).json({ error: 'Error interno del servidor' });
    }
};

module.exports = {
    backup,
    restore
};
